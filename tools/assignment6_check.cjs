/* Browser checks by PDF task; run with Playwright installed and --browser if needed. */
const { chromium } = require('playwright');
const { spawn } = require('node:child_process');
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '..');
const out = path.join(root, 'evidence/assignment6');
fs.mkdirSync(out, { recursive: true });
let server;
(async () => {
  server = spawn(process.execPath, [root + '/tools/serve.cjs'], { env: { ...process.env, PORT: '8098' } });
  await new Promise((resolve,reject) => {server.stdout.once('data',resolve);server.once('error',reject);});
  const index = process.argv.indexOf('--browser');
  const browser = await chromium.launch({ executablePath: index >= 0 ? process.argv[index + 1] : undefined,
    args: ['--no-sandbox','--single-process','--no-zygote','--disable-dev-shm-usage'] });
  const context = await browser.newContext({ viewport:{width:1440,height:1050}, permissions:['clipboard-read','clipboard-write'] });
  await context.route('https://code.jquery.com/**', route => route.fulfill({ path:root+'/vendor/jquery-4.0.0.min.js',contentType:'application/javascript' }));
  const page = await context.newPage();
  const errors = [], logs = [], tests = [];
  page.on('pageerror',error=>errors.push(String(error)));
  page.on('console',message=>logs.push(message.text()));
  const check = (task,name,condition)=>{assert.ok(condition,name);tests.push({task,name});};
  const go = file => page.goto('http://127.0.0.1:8098/'+file);
  const snap = async(name,selector)=>{const target=selector?page.locator(selector):page;await target.screenshot({path:out+'/'+name+'.png',animations:'disabled'});};
  await go('jquery.html');
  check(0,'jQuery 4.0.0 runs',await page.evaluate(()=>jQuery.fn.jquery)==='4.0.0');
  check(0,'Required console message appears',logs.includes('jQuery is ready!'));
  check(0,'Required CDN appears in head',await page.locator('head script[src="https://code.jquery.com/jquery-4.0.0.min.js"]').count()===1);
  check(1,'Entire catalogue renders',await page.locator('#jqResults article').count()===34);
  await page.locator('#jqSearch').fill('фантастика');
  check(1,'Genre filtering works live',await page.locator('#jqResults article').count()>0&&await page.locator('#jqResults article').count()<34);
  await page.keyboard.press('Escape');await snap('task1','#mainContent');
  const marks=await page.locator('#jqResults mark').allTextContents();
  check(3,'All matches in title/meta/description are highlighted',marks.length>0&&marks.every(s=>s.toLocaleLowerCase()==='фантастика'));
  check(3,'No unmarked matching text remains',await page.locator('#jqResults').evaluate(el=>{const walker=document.createTreeWalker(el,NodeFilter.SHOW_TEXT);while(walker.nextNode()){if(!walker.currentNode.parentElement.closest('mark')&&walker.currentNode.textContent.toLowerCase().includes('фантастика'))return false;}return true;}));
  await snap('task3', '#jqResults article:first-child');
  await page.locator('#jqSearch').fill('а');
  check(2,'Suggestions appear',await page.locator('#jqSuggestions button').count()>0);
  await snap('task2','#mainContent');
  await page.locator('#jqSearch').press('ArrowDown');await page.keyboard.press('ArrowUp');
  check(2,'Arrow Up wraps keyboard focus',await page.locator('#jqSuggestions button').last().evaluate(el=>el===document.activeElement));
  const title=await page.locator('#jqSuggestions button').last().innerText();await page.keyboard.press('Enter');
  check(2,'Enter selects suggestion',await page.locator('#jqSearch').inputValue()===title&&await page.locator('#jqSuggestions').isHidden());
  await page.locator('#jqSearch').fill('no-such-movie-123');
  check(1,'No-results state',await page.locator('#jqEmpty').isVisible()&&await page.locator('#jqResults article').count()===0);
  await page.locator('#jqSearch').fill('<script>alert(1)</script>');
  check(3,'Script-like search is inert',await page.locator('#jqResults script').count()===0);
  await page.locator('#jqSearch').fill('');check(1,'Clear restores all items',await page.locator('#jqResults article').count()===34);
  await go('jquery-ux.html');
  await page.waitForTimeout(350);const intermediate=Number(await page.locator('.jq-counter').first().innerText());
  check(5,'Counter has an intermediate animated value',intermediate>0&&intermediate<34);await snap('task5-animation','section.card');
  await page.waitForTimeout(1300);check(5,'Counters end at exact targets',JSON.stringify((await page.locator('.jq-counter').allTextContents()).map(s=>s.trim()))===JSON.stringify(['34','22','9']));
  await snap('task5','section.card');
  for(const pair of [['',''],['   ','   '],['Ali','\t \n']]){
    await page.locator('#jqName').fill(pair[0]);await page.locator('#jqMessage').fill(pair[1]);await page.locator('#jqSubmit').click();
    check(6,'Invalid/whitespace input does not start submission',await page.locator('#jqSubmit').isEnabled()&&(await page.locator('#jqFormStatus').innerText()).length>0);
  }
  await snap('task6-invalid','#jqForm');
  await page.locator('#jqName').fill('  Symbat  ');await page.locator('#jqMessage').fill('  Interstellar  ');
  await page.locator('#jqSubmit').click();
  check(6,'Spinner, Please wait and disabled state appear',await page.locator('.jq-spinner').isVisible()&&await page.locator('#jqSubmit').isDisabled()&&(await page.locator('#jqSubmit').innerText()).includes('Please wait'));
  await snap('task6','#jqForm');
  await page.locator('#jqForm').evaluate(form=>form.dispatchEvent(new Event('submit',{cancelable:true,bubbles:true})));
  await page.waitForTimeout(1700);check(6,'Button returns to normal after delay',await page.locator('#jqSubmit').isEnabled()&&await page.locator('.jq-spinner').count()===0);
  check(7,'Form completion shows toast',await page.locator('#jqToast').isVisible());
  await page.evaluate(()=>scrollTo(0,document.documentElement.scrollHeight));await page.waitForTimeout(100);
  check(4,'Bottom of page reaches 100 percent',Number(await page.locator('#jqProgress').getAttribute('aria-valuenow'))===100);await snap('task4');
  await page.evaluate(()=>scrollTo(0,0));await page.waitForTimeout(100);check(4,'Top returns to zero',Number(await page.locator('#jqProgress').getAttribute('aria-valuenow'))===0);
  await go('jquery-tools.html');
  await page.locator('#jqNotify').click();check(7,'Real watchlist entry is added',await page.locator('#jqSavedList li').count()===1);await snap('task7');
  await page.reload();check(7,'Watchlist survives reload',await page.locator('#jqSavedList li').count()===1);
  await page.locator('#jqNotify').click();check(7,'Removal updates list and toast',await page.locator('#jqSavedList li').count()===0&&await page.locator('#jqToast').isVisible());
  await page.waitForTimeout(2900);check(7,'Toast fades away',await page.locator('#jqToast').isHidden());
  await page.locator('#jqCopy').click();await page.waitForFunction(()=>document.querySelector('#jqCopy').textContent.includes('✓'));
  check(8,'Clipboard contains exact share text',await page.evaluate(()=>navigator.clipboard.readText())===await page.locator('#jqShare').innerText());
  check(8,'Checkmark and tooltip displayed',await page.locator('#jqCopyTip').isVisible());await snap('task8','#mainContent');
  await page.waitForTimeout(2800);check(8,'Tooltip and label reset',await page.locator('#jqCopyTip').isHidden()&&!(await page.locator('#jqCopy').innerText()).includes('✓'));
  await page.evaluate(()=>{navigator.clipboard.writeText=()=>Promise.reject(new Error('denied'));});
  await page.locator('#jqCopy').click();await page.waitForTimeout(100);
  check(8,'Clipboard rejection never reports success',!(await page.locator('#jqCopy').innerText()).includes('✓')&&(await page.locator('#jqToast').innerText()).includes('рұқсат'));
  check(9,'One poster per catalogue entry',await page.locator('.jq-lazy').count()===34);
  const pending=await page.locator('.jq-lazy[data-src]').count();check(9,'Offscreen images retain placeholders',pending>0);
  await snap('task9');
  const height=await page.evaluate(()=>document.documentElement.scrollHeight);
  for(let y=0;y<height;y+=650){await page.evaluate(y=>scrollTo(0,y),y);await page.waitForTimeout(30);}
  await page.waitForTimeout(400);
  check(9,'All visited images acquire real sources',await page.locator('.jq-lazy[data-src]').count()===0);
  check(9,'Images decode without broken sources',await page.locator('.jq-lazy').evaluateAll(async images=>{await Promise.all(images.map(img=>img.decode().catch(()=>{})));return images.every(img=>img.naturalWidth>0);}));
  await page.emulateMedia({reducedMotion:'reduce'});await go('jquery-ux.html');
  check(5,'Reduced-motion counters use final values',await page.locator('.jq-counter').first().innerText()==='34');
  await page.emulateMedia({reducedMotion:'no-preference'});
  let viewportChecks=0;
  for(const width of [375,768,1440]){await page.setViewportSize({width,height:900});for(const file of ['jquery.html','jquery-ux.html','jquery-tools.html']){await go(file);check('UX',file+' responsive '+width,await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));viewportChecks++;}}
  await context.route('https://code.jquery.com/**',route=>route.abort());await go('jquery.html');
  check(0,'CDN failure loads local fallback',await page.evaluate(()=>jQuery.fn.jquery)==='4.0.0'&&await page.locator('#jqResults article').count()===34);
  check('runtime','No uncaught JavaScript errors',errors.length===0);
  const result={checkedAt:new Date().toISOString(),browser:await browser.version(),checks:tests.length,viewportChecks,tests,errors};
  fs.writeFileSync(out+'/qa-results.json',JSON.stringify(result,null,2));console.log(JSON.stringify(result,null,2));
  await browser.close();server.kill();
})().catch(error=>{server?.kill();console.error(error);process.exit(1);});
